#!/usr/bin/env python3
"""Single source of truth for the IE4060 assignment maze geometry.

Wall centre-line segments are taken from MAZE_REFERENCE.md and checked against
Figure 1 of assignment_brief.pdf by pixel measurement (see docs/map_provenance.md).
The reference document omitted one wall (upper_right_v); it is added here.

Generates:
  * the Gazebo world  (ros2_ws/src/maze_bringup/worlds/assignment_maze.sdf)
  * a GEOMETRY-DERIVED reference occupancy map (maps/reference/ground_truth_maze.*)
    -- this is NOT a SLAM map and must never be presented as one.
"""
import argparse
import math
import os

# id, x0, y0, x1, y1 (metres, maze centre at origin, +x right, +y up in Figure 1)
SEGMENTS = [
    ("outer_top", -1.5, 1.5, 1.5, 1.5),
    ("outer_bottom", -1.5, -1.5, 1.5, -1.5),
    ("outer_left", -1.5, -1.5, -1.5, 1.5),
    ("outer_right", 1.5, -1.5, 1.5, 1.5),
    ("upper_vertical1", -0.5, 1.0, -0.5, 1.5),
    ("upper_vertical2", 0.5, 1.0, 0.5, 1.5),
    ("left_vertical", -1.0, -0.5, -1.0, 1.0),
    ("upper_middle", 0.0, 0.5, 0.0, 1.0),
    ("upper_bar", -0.5, 0.5, 1.0, 0.5),
    ("center_left", -0.5, 0.0, -0.5, 0.5),
    ("center_right", 0.5, 0.0, 0.5, 0.5),
    ("right_bar", 0.5, 0.0, 1.5, 0.0),
    ("lower_middle", 0.0, -0.5, 0.0, 0.0),
    ("middle_bar", -1.0, -0.5, 0.5, -0.5),
    ("lower_right", 1.0, -1.0, 1.0, 0.0),
    ("bottom_left_bar", -1.5, -1.0, -1.0, -1.0),
    ("bottom_bar", -0.5, -1.0, 1.0, -1.0),
    ("upper_right_v", 1.0, 0.5, 1.0, 1.0),  # present in Figure 1, missing in MAZE_REFERENCE.md
]

WALL_THICKNESS = 0.05  # m (not specified by the brief; chosen and documented)
WALL_HEIGHT = 0.30     # m (> LiDAR height 0.182 m)
WORLD_REVISION = "maze_v1_18seg_t0.05_h0.30"
PHYSICS_ENGINE = "gz-physics-dartsim-plugin"  # default engine; bullet-featherstone rejected the model (docs/progress.md)


def wall_boxes():
    """Yield (name, cx, cy, length, yaw) boxes; ends extended by half thickness so corners close."""
    for name, x0, y0, x1, y1 in SEGMENTS:
        length = math.hypot(x1 - x0, y1 - y0) + WALL_THICKNESS
        yaw = math.atan2(y1 - y0, x1 - x0)
        yield name, (x0 + x1) / 2.0, (y0 + y1) / 2.0, length, yaw


def world_sdf():
    links = []
    for name, cx, cy, length, yaw in wall_boxes():
        size = f"{length:.4f} {WALL_THICKNESS:.4f} {WALL_HEIGHT:.4f}"
        links.append(f"""      <link name="{name}">
        <pose>{cx:.4f} {cy:.4f} {WALL_HEIGHT / 2:.4f} 0 0 {yaw:.6f}</pose>
        <collision name="{name}_collision"><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="{name}_visual"><geometry><box><size>{size}</size></box></geometry>
          <material><ambient>0.55 0.55 0.6 1</ambient><diffuse>0.55 0.55 0.6 1</diffuse></material></visual>
      </link>""")
    walls = "\n".join(links)
    return f"""<?xml version="1.0"?>
<!-- GENERATED by tools/maze_geometry.py ({WORLD_REVISION}). Edit the generator, not this file. -->
<sdf version="1.9">
  <world name="assignment_maze">
    <physics name="1ms" type="ignored">
      <max_step_size>0.006</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics">
      <engine><filename>{PHYSICS_ENGINE}</filename></engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry>
          <material><ambient>0.85 0.85 0.85 1</ambient><diffuse>0.85 0.85 0.85 1</diffuse></material></visual>
      </link>
    </model>

    <model name="maze">
      <static>true</static>
{walls}
    </model>
  </world>
</sdf>
"""


def point_segment_distance(px, py, x0, y0, x1, y1):
    dx, dy = x1 - x0, y1 - y0
    t = max(0.0, min(1.0, ((px - x0) * dx + (py - y0) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (x0 + t * dx), py - (y0 + t * dy))


def occupied(x, y):
    """True if world point (x, y) lies inside any wall box (axis-aligned walls only)."""
    half = WALL_THICKNESS / 2.0
    for _, x0, y0, x1, y1 in SEGMENTS:
        if x0 == x1:
            if abs(x - x0) <= half and min(y0, y1) - half <= y <= max(y0, y1) + half:
                return True
        elif y0 == y1:
            if abs(y - y0) <= half and min(x0, x1) - half <= x <= max(x0, x1) + half:
                return True
        else:
            raise ValueError("rotated wall not supported by rasteriser")
    return False


def clearance(x, y):
    """Distance from point to nearest wall surface (negative inside)."""
    return min(point_segment_distance(x, y, *s[1:]) for s in SEGMENTS) - WALL_THICKNESS / 2.0


def reference_map(out_base, resolution=0.02, margin=0.1):
    lo = -1.5 - WALL_THICKNESS / 2 - margin
    size = int(round((3.0 + WALL_THICKNESS + 2 * margin) / resolution))
    rows = []
    for r in range(size):
        y = lo + (size - 1 - r + 0.5) * resolution  # image row 0 = top = max y
        row = bytearray()
        for c in range(size):
            x = lo + (c + 0.5) * resolution
            inside = -1.5 <= x <= 1.5 and -1.5 <= y <= 1.5
            if occupied(x, y):
                row.append(0)
            elif inside:
                row.append(254)
            else:
                row.append(205)  # unknown outside the maze
        rows.append(bytes(row))
    with open(out_base + ".pgm", "wb") as f:
        f.write(f"P5\n{size} {size}\n255\n".encode())
        for row in rows:
            f.write(row)
    name = os.path.basename(out_base)
    with open(out_base + ".yaml", "w") as f:
        f.write(f"""# GEOMETRY-DERIVED REFERENCE MAP ({WORLD_REVISION}) - NOT a SLAM result.
image: {name}.pgm
mode: trinary
resolution: {resolution}
origin: [{lo:.4f}, {lo:.4f}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
""")
    return size, lo


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--world", default=os.path.join(root, "ros2_ws/src/maze_bringup/worlds/assignment_maze.sdf"))
    ap.add_argument("--map", default=os.path.join(root, "maps/reference/ground_truth_maze"))
    a = ap.parse_args()
    os.makedirs(os.path.dirname(a.world), exist_ok=True)
    os.makedirs(os.path.dirname(a.map), exist_ok=True)
    with open(a.world, "w") as f:
        f.write(world_sdf())
    size, lo = reference_map(a.map)
    print(f"world -> {a.world}\nmap   -> {a.map}.yaml ({size}x{size}, origin {lo:.3f})")
    # self-checks: known wall point and known free cell centre
    assert occupied(-1.5, 0.0) and occupied(1.0, 0.75) and not occupied(-1.25, -1.25)
    print("clearance at cell centre (-1.25,-1.25): %.3f m" % clearance(-1.25, -1.25))
