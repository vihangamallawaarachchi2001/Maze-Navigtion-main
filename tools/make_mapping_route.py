#!/usr/bin/env python3
"""Generate the scripted mapping tour (depth-first visit of every maze cell, with backtracking).

Waypoints are expressed in the SLAM map frame, which coincides with the Gazebo world frame
(odometry is pose-derived, docs/map_provenance.md).
The tour only replaces keyboard teleoperation; the map itself is built by SLAM Toolbox from LiDAR.
"""
import os, sys, yaml
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from maze_geometry import SEGMENTS  # noqa: E402

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = os.path.join(root, "ros2_ws/src/maze_bringup/config")
spawn = yaml.safe_load(open(os.path.join(cfg, "safe_spawn.yaml")))

def blocked(a, b):
    (i, j), (k, l) = a, b
    for _, x0, y0, x1, y1 in SEGMENTS:
        if i != k:
            X, yc = -1.5 + 0.5 * max(i, k), -1.25 + 0.5 * j
            if x0 == x1 == X and min(y0, y1) < yc < max(y0, y1): return True
        else:
            Y, xc = -1.5 + 0.5 * max(j, l), -1.25 + 0.5 * i
            if y0 == y1 == Y and min(x0, x1) < xc < max(x0, x1): return True
    return False

start = (round((spawn["safe_x"] + 1.25) / 0.5), round((spawn["safe_y"] + 1.25) / 0.5))
seen, tour = {start}, [start]
def dfs(c):
    for d in ((1, 0), (0, 1), (-1, 0), (0, -1)):
        n = (c[0] + d[0], c[1] + d[1])
        if 0 <= n[0] < 6 and 0 <= n[1] < 6 and n not in seen and not blocked(c, n):
            seen.add(n); tour.append(n); dfs(n); tour.append(c)
dfs(start)
# merge collinear moves
pts = [tour[0]]
for k in range(1, len(tour) - 1):
    a, b, c = pts[-1], tour[k], tour[k + 1]
    if (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]) != 0 or (c[0]-b[0], c[1]-b[1]) != (b[0]-a[0], b[1]-a[1]) and (a != b):
        pts.append(b)
pts.append(tour[-1])
wp = [[round(-1.25 + 0.5 * i, 3), round(-1.25 + 0.5 * j, 3)] for i, j in pts]
out = os.path.join(cfg, "mapping_route.yaml")
with open(out, "w") as f:
    f.write("# GENERATED by tools/make_mapping_route.py - odom-frame waypoints for the scripted mapping drive\n")
    yaml.safe_dump({"frame": "map", "cells_visited": len(seen), "waypoints": wp}, f)
print(f"{len(seen)} cells, {len(tour)} tour steps, {len(wp)} waypoints -> {out}")
